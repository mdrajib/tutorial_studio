// One ElevenLabs narration MP3 per scene per language from projects/<name>/scripts/*.md into
// projects/<name>/audio/<video>/<scene>-<slug>-<lang>.mp3, plus word timings (<clip>.words.json) for
// record.js and captions.js, a full padded track per video per language, and audio/README.md.
// Existing clips are skipped, so re-running only fills gaps.
//   node engine/audio.js brandluka                     (everything missing)
//   node engine/audio.js brandluka A1                  (only video A1)
//   node engine/audio.js brandluka --force A1-S04      (retake one scene, all languages; or A1-S04-bn)
//   node engine/audio.js brandluka --index             (index only, no API calls)
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { project, scripts, clip, slotOf, duration } = require('./lib');

const args = process.argv.slice(2);
const p = project(args[0]);
const force = args.includes('--force') ? args[args.indexOf('--force') + 1] : null;
const indexOnly = args.includes('--index');
const only = args.slice(1).find((a) => !a.startsWith('--') && a !== force);
const { voiceId, modelId = 'eleven_v4' } = p.config.voice || {};
const KEY = process.env.ELEVENLABS_API_KEY;
const videos = scripts(p).filter((v) => !only || v.id === only);
if (only && !videos.length) throw new Error(`no video ${only} in projects/${p.name}/scripts`);

async function tts(text, file) {
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voiceId}?output_format=mp3_44100_128`, {
    method: 'POST',
    headers: { 'xi-api-key': KEY, 'Content-Type': 'application/json' },
    body: JSON.stringify({ text, model_id: modelId }),
  });
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
}

async function align(file, text) {
  const form = new FormData();
  form.append('file', new Blob([fs.readFileSync(file)]), path.basename(file));
  form.append('text', text);
  const res = await fetch('https://api.elevenlabs.io/v1/forced-alignment', { method: 'POST', headers: { 'xi-api-key': KEY }, body: form });
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  const { words } = await res.json();
  return words.filter((w) => w.text.trim()).map((w) => ({ text: w.text, start: w.start, end: w.end }));
}

(async () => {
  if (!indexOnly && !KEY) throw new Error('ELEVENLABS_API_KEY missing (root .env or the project .env)');
  if (!indexOnly && !voiceId) throw new Error(`projects/${p.name}/project.json: voice.voiceId missing`);
  let failed = 0;
  const each = (fn) => videos.flatMap((v) => v.scenes.flatMap((s) => p.languages.map((lang) => () => fn(v, s, lang))));

  if (!indexOnly)
    for (const job of each(async (v, s, lang) => {
      const file = clip(p, v, s, lang);
      const forced = force && (force === s.id || force === `${s.id}-${lang}`);
      if (!s.text[lang]) return console.warn(`skip ${s.id}-${lang}: no **${lang.toUpperCase()}:** line`);
      if (fs.existsSync(file) && !forced) return;
      try {
        await tts(s.text[lang], file);
        console.log(`ok   ${path.relative(p.audio, file)}  ${duration(file).toFixed(1)}s`);
      } catch (e) {
        failed++;
        console.error(`FAIL ${s.id}-${lang}: ${e.message}`);
      }
    })) await job();

  // Word timings, redone whenever the clip is newer than them.
  if (!indexOnly)
    for (const job of each(async (v, s, lang) => {
      const file = clip(p, v, s, lang);
      const out = clip(p, v, s, lang, '.words.json');
      if (!fs.existsSync(file) || (fs.existsSync(out) && fs.statSync(out).mtimeMs > fs.statSync(file).mtimeMs)) return;
      try {
        fs.writeFileSync(out, JSON.stringify(await align(file, s.text[lang])));
        console.log(`ok   ${path.relative(p.audio, out)}`);
      } catch (e) {
        failed++;
        console.error(`FAIL ${s.id}-${lang} timings: ${e.message}`);
      }
    })) await job();

  // Index: one table per video, real lengths, and the record-to slot.
  const L = p.languages;
  const mmss = (x) => `${Math.floor(x / 60)}:${String(Math.round(x % 60)).padStart(2, '0')}`;
  const out = [
    `# ${p.name}: narration audio`,
    '',
    `Generated by \`engine/audio.js ${p.name}\` (ElevenLabs voice \`${voiceId}\`, model \`${modelId}\`).`,
    '**Record to** = the longest language plus 1 s; record.js holds each scene for exactly that long.',
    '`<video>-full-<lang>.mp3` = the whole video, each scene padded to its slot, ready to drop under the take at 0:00.',
    '',
  ];
  for (const v of videos) {
    const total = Object.fromEntries(L.map((l) => [l, 0]));
    const rows = v.scenes.map((s) => {
      const d = Object.fromEntries(L.map((l) => [l, fs.existsSync(clip(p, v, s, l)) ? duration(clip(p, v, s, l)) : null]));
      L.forEach((l) => (total[l] += d[l] || 0));
      const rec = L.every((l) => d[l] != null) ? `${slotOf(p, v, s)} s` : '-';
      return `| ${s.id} | ${s.title} | ${L.map((l) => (d[l] == null ? 'missing' : `${d[l].toFixed(1)} s`)).join(' | ')} | ${rec} |`;
    });
    out.push(
      `## ${v.id}. ${v.title}`, '',
      `Folder: \`${v.dir}/\` · total ${L.map((l) => `${l.toUpperCase()} ${mmss(total[l])}`).join(' · ')}`, '',
      `| Scene | Title | ${L.map((l) => l.toUpperCase()).join(' | ')} | Record to |`,
      `|---|---|${L.map(() => '---|').join('')}---|`,
      ...rows, ''
    );
  }
  fs.mkdirSync(p.audio, { recursive: true });
  fs.writeFileSync(path.join(p.audio, 'README.md'), out.join('\n'));

  // Full track per video per language, each scene padded with silence to its slot.
  for (const v of videos) {
    if (!v.scenes.length || v.scenes.some((s) => L.some((l) => !fs.existsSync(clip(p, v, s, l))))) continue;
    const slots = v.scenes.map((s) => slotOf(p, v, s));
    for (const lang of L) {
      const files = v.scenes.map((s) => clip(p, v, s, lang));
      const full = path.join(p.audio, v.dir, `${v.id}-full-${lang}.mp3`);
      // Up to date: leave it (it may be open in the editor, and ffmpeg can't overwrite a locked file).
      if (fs.existsSync(full) && files.every((f) => fs.statSync(full).mtimeMs >= fs.statSync(f).mtimeMs)) continue;
      const pads = slots.map((d, i) => `[${i}:a]apad=whole_dur=${d}[a${i}]`).join(';');
      // loudnorm: raw ElevenLabs clips sit near -21 dB mean, too quiet for YouTube.
      const cat = slots.map((_, i) => `[a${i}]`).join('') + `concat=n=${slots.length}:v=0:a=1,loudnorm=I=-16:TP=-1.5:LRA=11,aresample=44100[out]`;
      try {
        execFileSync(require('ffmpeg-static'), [
          '-y', '-v', 'error', ...files.flatMap((f) => ['-i', f]),
          '-filter_complex', `${pads};${cat}`, '-map', '[out]', '-b:a', '128k', full,
        ], { stdio: 'pipe' });
        console.log(`ok   ${path.relative(p.audio, full)}`);
      } catch (e) {
        failed++;
        console.error(`FAIL ${v.id}-full-${lang}.mp3: ${String(e.stderr || e.message).split('\n')[0]}`);
      }
    }
  }
  console.log(`index written; ${failed} failed`);
  if (failed) process.exitCode = 1;
})().catch((e) => {
  console.error(e.message);
  process.exitCode = 1;
});
